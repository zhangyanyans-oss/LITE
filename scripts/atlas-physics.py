def main():
    OUT.mkdir(parents=True, exist_ok=True)
    doc = fitz.open(PDF)
    pdf_cache = {}
    optics_imgs = [Image.open(p).convert("RGB") for p in OPTICS]
    band_cache = {}

    items = []
    for meta in ITEMS:
        src = meta["src"]
        if src[0] == "pdf":
            _, page, idx = src
            if page not in band_cache:
                band_cache[page] = page_bands(doc[page - 1])
            img, bands = band_cache[page]
            if idx > len(bands) or bands[idx - 1] is None:
                raise SystemExit(f"{meta['id']}: 第 {page} 页第 {idx} 个图组不存在（切图结果与核对时不一致）")
            crop = crop_band(img, bands[idx - 1])
        else:
            _, which, box = src
            crop = crop_box(optics_imgs[which], box)

        fname = f"{meta['id']}.png"
        crop.save(OUT / fname, optimize=True)
        entry = {
            "id": meta["id"],
            "file": fname,
            "name": meta["name"],
            "kind": meta["kind"],
            "aliases": meta["aliases"],
            "tags": meta["tags"],
            "devices": meta["devices"],
            "assembly": meta["assembly"],
            "width": crop.width,
            "height": crop.height,
        }
        if meta["note"]:
            entry["note"] = meta["note"]
        items.append(entry)
        print(f"  {meta['id']} {crop.width}x{crop.height} {meta['name']}")

    lib = {
        "version": 1,
        "subject": "physics",
        "source": "人教版初中物理实验专题复习讲义（89 页扫描）+ 初中物理光路图大全（表格图）",
        "baseUrl": "/atlas/",
        "note": "kind: setup=实验装置图（甲/乙/丙成组的是对比图）；principle=原理图/光路图，讲规律时引用；两者都不是反例",
        "items": items,
    }
    Path("config/diagram/atlas/physics.json").write_text(
        json.dumps(lib, ensure_ascii=False, indent=1), encoding="utf-8"
    )
    print("physics.json <-", len(items), "条")

    write_overview(items)


