# ── 切图：一页里的图组 ────────────────────────────────────────────
def page_bands(pg):
    """返回 [(y0, y1, x0, x1)]：挖掉文字框后，绘图笔画按行合并成的带"""
    pm = pg.get_pixmap(dpi=DPI)
    img = Image.frombytes("RGB", (pm.width, pm.height), pm.samples)
    ink = np.asarray(img.convert("L")).astype(np.int16) < 200

    sx, sy = img.width / pg.rect.width, img.height / pg.rect.height
    tmask = np.zeros_like(ink)
    for b in pg.get_text("blocks"):
        x0, y0, x1, y1 = b[:4]
        tmask[
            max(0, int(y0 * sy) - 3) : int(y1 * sy) + 3,
            max(0, int(x0 * sx) - 3) : int(x1 * sx) + 3,
        ] = True
    gfx = ink & ~tmask

    active = gfx.sum(axis=1) > 8
    bands, start = [], None
    for y, v in enumerate(active):
        if v and start is None:
            start = y
        elif not v and start is not None:
            if y - start >= 40:
                bands.append([start, y])
            elif bands and start - bands[-1][1] < 28:
                bands[-1][1] = y
            start = None
    if start is not None and len(active) - start >= 40:
        bands.append([start, len(active)])

    merged = []
    for b in bands:
        if merged and b[0] - merged[-1][1] < 28:
            merged[-1][1] = b[1]
        else:
            merged.append(b)

    out = []
    for y0, y1 in merged:
        sub = gfx[y0:y1]
        xs = np.where(sub.sum(axis=0) > 2)[0]
        if len(xs) == 0:
            continue
        x0, x1 = int(xs[0]), int(xs[-1])
        if x1 - x0 < 110 or y1 - y0 < 60 or int(sub.sum()) < 700:
            out.append(None)  # 占位：保持序号稳定（与核对时看到的编号一致）
            continue
        out.append((y0, y1, x0, x1))
    return img, out


def crop_band(img, band, pad=8, pad_bottom=6):
    y0, y1, x0, x1 = band
    box = (
        max(0, x0 - pad),
        max(0, y0 - pad),
        min(img.width, x1 + pad),
        min(img.height, y1 + pad + pad_bottom),
    )
    return img.crop(box)


def crop_box(img, box):
    return img.crop(box)


